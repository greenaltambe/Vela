// Immutable by contract: `Instant` is an external type the Compose compiler cannot prove stable, which made every card compare by
// identity and recompose whenever the feed pipeline rebuilt the list. With this, an unchanged video lets its card be skipped.
@androidx.compose.runtime.Immutable
data class VideoSummary(
    val id: String,
    val title: String,
    val channelId: String,
    val channelName: String,
    val thumbnailUrl: String? = null,
    val durationSeconds: Long? = null,
    val viewCount: Long? = null,
    val isShort: Boolean = false,
    /** A live stream (or a premiere that has not ended). */
    val isLive: Boolean = false,
    /** When the video was published, if the source says (the RSS feed does; search results mostly don't). */
    val uploadedAt: Instant? = null,
    /** Set when DeArrow replaced [title] / [thumbnailUrl]: what they were, for "show original". */
    val originalTitle: String? = null,
    val originalThumbnailUrl: String? = null,
    /** The uploader's picture, when the source gives one with the item. */
    val channelAvatarUrl: String? = null,
    /** How long ago it was published, as the source worded it ("3 days ago"), for feeds that give no exact date. */
    val publishedText: String? = null,
    /** How much of the video the signed-in account has watched (0..100), when the feed reports it; null = not reported. */
    val watchedPercent: Int? = null,
)

